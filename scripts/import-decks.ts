import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import Papa from "papaparse";
import { buildDeck, parseDeckConfig, type CsvRow, type DeckReport } from "../core/deck";
import type { Deck } from "../core/types";

type LoadedDeck = {
  deck: Deck;
  report: DeckReport;
};

const dataDir = join(process.cwd(), "data", "decks");
const generatedDir = join(process.cwd(), "content", "generated");

function printItems(label: string, items: string[]): void {
  if (items.length === 0) {
    console.log(`${label}: none`);
    return;
  }

  console.log(`${label}:`);

  for (const item of items) {
    console.log(`  ${item}`);
  }
}

function printReport(name: string, report: DeckReport): void {
  console.log(`\n${name}`);
  console.log(`Words imported: ${report.wordCount}`);
  printItems(
    "Missing examples",
    report.missingExamples.map(({ row, word }) => `${word} (row ${row})`),
  );
  printItems(
    "Missing translations",
    report.missingTranslations.map(({ row, word }) => `${word} (row ${row})`),
  );
  printItems(
    "Different forms",
    report.differentForms.map(({ word, form }) => `${word} -> ${form}`),
  );
  printItems(
    "No cloze",
    report.noCloze.map(({ row, word }) => `${word} (row ${row})`),
  );
  printItems("Warnings", report.warnings);
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function readConfigFiles(): string[] {
  try {
    return readdirSync(dataDir)
      .filter((name) => name.endsWith(".deck.json"))
      .sort();
  } catch (error) {
    console.error(`Cannot read ${dataDir}: ${errorMessage(error)}`);
    process.exit(1);
  }
}

const configFiles = readConfigFiles();

if (configFiles.length === 0) {
  console.error(`No deck configs found in ${dataDir}.`);
  process.exit(1);
}

const loaded: LoadedDeck[] = [];
let failed = false;

for (const configFile of configFiles) {
  const configPath = join(dataDir, configFile);
  let configValue: unknown;

  try {
    configValue = JSON.parse(readFileSync(configPath, "utf8").replace(/^\uFEFF/, ""));
  } catch (error) {
    console.error(`Cannot read ${configFile}: ${errorMessage(error)}`);
    failed = true;
    continue;
  }

  const parsedConfig = parseDeckConfig(configValue);

  if (!parsedConfig.ok) {
    console.error(`Invalid deck config ${configFile}:`);

    for (const error of parsedConfig.errors) {
      console.error(`  ${error}`);
    }

    failed = true;
    continue;
  }

  const config = parsedConfig.config;
  const csvPath = join(dataDir, config.file);
  let csvText: string;

  try {
    csvText = readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "");
  } catch (error) {
    console.error(`Cannot read ${config.file}: ${errorMessage(error)}`);
    failed = true;
    continue;
  }

  const parsedCsv = Papa.parse<CsvRow>(csvText, {
    header: true,
    skipEmptyLines: true,
  });

  if (parsedCsv.errors.length > 0) {
    console.error(`Invalid CSV ${config.file}:`);

    for (const error of parsedCsv.errors) {
      const row = error.row === undefined ? "" : ` row ${error.row + 2}:`;
      console.error(` ${row} ${error.message}`);
    }

    failed = true;
    continue;
  }

  const result = buildDeck(config, parsedCsv.meta.fields ?? [], parsedCsv.data);

  if (!result.ok) {
    printReport(config.name, result.report);
    console.error(`Deck "${config.id}" failed:`);

    for (const error of result.errors) {
      console.error(`  ${error}`);
    }

    failed = true;
    continue;
  }

  printReport(config.name, result.report);
  loaded.push({ deck: result.deck, report: result.report });
}

if (failed) {
  console.error("\nImport failed; no files were written.");
  process.exit(1);
}

mkdirSync(generatedDir, { recursive: true });

const imports: string[] = [];
const names: string[] = [];

for (const { deck } of loaded) {
  writeFileSync(
    join(generatedDir, `${deck.id}.json`),
    `${JSON.stringify(deck, null, 2)}\n`,
    "utf8",
  );

  const name = `deck_${deck.id.replace(/[^a-z0-9_]/gi, "_")}`;
  imports.push(`import ${name} from "./${deck.id}.json";`);
  names.push(name);
}

const registry = [
  "// Generated by scripts/import-decks.ts. Do not edit by hand.",
  'import type { Deck } from "@/core/types";',
  ...imports,
  "",
  `export const decks: Deck[] = [${names.join(", ")}];`,
  "",
].join("\n");

writeFileSync(join(generatedDir, "index.ts"), registry, "utf8");
console.log(`\nWrote ${loaded.length} deck file(s) to content/generated.`);
